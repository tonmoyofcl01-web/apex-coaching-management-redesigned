-- Run this script while connected as APEX_CMS_APP to the intended PDB.
-- Non-destructive: creates tables only. It does not drop or truncate data.

CREATE TABLE ADMINS (
  ADMIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FULL_NAME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(180) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(255) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE STUDENTS (
  STUDENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_CODE VARCHAR2(30) NOT NULL UNIQUE,
  FULL_NAME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(180),
  PHONE VARCHAR2(30) NOT NULL,
  GUARDIAN_NAME VARCHAR2(120),
  GUARDIAN_PHONE VARCHAR2(30),
  ADDRESS VARCHAR2(500),
  DATE_OF_BIRTH DATE,
  GENDER VARCHAR2(20),
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_STUDENT_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE TEACHERS (
  TEACHER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FULL_NAME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(180),
  PHONE VARCHAR2(30) NOT NULL,
  SPECIALIZATION VARCHAR2(150),
  JOIN_DATE DATE DEFAULT SYSDATE,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_TEACHER_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE COURSES (
  COURSE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COURSE_NAME VARCHAR2(150) NOT NULL,
  DESCRIPTION VARCHAR2(1000),
  DURATION_MONTHS NUMBER(3) DEFAULT 1 NOT NULL,
  COURSE_FEE NUMBER(12,2) DEFAULT 0 NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT CK_COURSE_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE')),
  CONSTRAINT CK_COURSE_FEE CHECK (COURSE_FEE >= 0)
);

CREATE TABLE BATCHES (
  BATCH_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BATCH_NAME VARCHAR2(120) NOT NULL,
  COURSE_ID NUMBER NOT NULL,
  TEACHER_ID NUMBER,
  START_DATE DATE,
  END_DATE DATE,
  SCHEDULE VARCHAR2(180),
  CAPACITY NUMBER(5) DEFAULT 30 NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_BATCH_COURSE FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID),
  CONSTRAINT FK_BATCH_TEACHER FOREIGN KEY (TEACHER_ID) REFERENCES TEACHERS(TEACHER_ID),
  CONSTRAINT CK_BATCH_STATUS CHECK (STATUS IN ('ACTIVE','COMPLETED','CANCELLED')),
  CONSTRAINT CK_BATCH_CAPACITY CHECK (CAPACITY > 0)
);

CREATE TABLE ENROLLMENTS (
  ENROLLMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL,
  BATCH_ID NUMBER NOT NULL,
  ENROLLMENT_DATE DATE DEFAULT SYSDATE NOT NULL,
  TOTAL_FEE NUMBER(12,2) DEFAULT 0 NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_ENROLL_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID),
  CONSTRAINT FK_ENROLL_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_ID),
  CONSTRAINT CK_ENROLL_STATUS CHECK (STATUS IN ('ACTIVE','COMPLETED','CANCELLED')),
  CONSTRAINT CK_ENROLL_FEE CHECK (TOTAL_FEE >= 0),
  CONSTRAINT UQ_STUDENT_BATCH UNIQUE (STUDENT_ID, BATCH_ID)
);

CREATE TABLE PAYMENTS (
  PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL,
  ENROLLMENT_ID NUMBER,
  AMOUNT NUMBER(12,2) NOT NULL,
  PAYMENT_METHOD VARCHAR2(30) DEFAULT 'CASH' NOT NULL,
  PAYMENT_DATE DATE DEFAULT SYSDATE NOT NULL,
  REFERENCE_NO VARCHAR2(100),
  STATUS VARCHAR2(20) DEFAULT 'PAID' NOT NULL,
  NOTES VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_PAYMENT_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID),
  CONSTRAINT FK_PAYMENT_ENROLL FOREIGN KEY (ENROLLMENT_ID) REFERENCES ENROLLMENTS(ENROLLMENT_ID),
  CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT > 0),
  CONSTRAINT CK_PAYMENT_METHOD CHECK (PAYMENT_METHOD IN ('CASH','BKASH','NAGAD','BANK','CARD','OTHER')),
  CONSTRAINT CK_PAYMENT_STATUS CHECK (STATUS IN ('PAID','PENDING','REFUNDED'))
);

CREATE TABLE ATTENDANCE (
  ATTENDANCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL,
  BATCH_ID NUMBER NOT NULL,
  ATTENDANCE_DATE DATE DEFAULT SYSDATE NOT NULL,
  STATUS VARCHAR2(20) NOT NULL,
  REMARKS VARCHAR2(500),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_ATT_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID),
  CONSTRAINT FK_ATT_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BATCHES(BATCH_ID),
  CONSTRAINT CK_ATT_STATUS CHECK (STATUS IN ('PRESENT','ABSENT','LATE')),
  CONSTRAINT UQ_ATTENDANCE_DAY UNIQUE (STUDENT_ID, BATCH_ID, ATTENDANCE_DATE)
);

CREATE INDEX IX_STUDENTS_NAME ON STUDENTS(FULL_NAME);
CREATE INDEX IX_STUDENTS_PHONE ON STUDENTS(PHONE);
CREATE INDEX IX_ENROLL_BATCH ON ENROLLMENTS(BATCH_ID);
CREATE INDEX IX_PAYMENT_DATE ON PAYMENTS(PAYMENT_DATE);
CREATE INDEX IX_ATT_DATE ON ATTENDANCE(ATTENDANCE_DATE);

COMMIT;
