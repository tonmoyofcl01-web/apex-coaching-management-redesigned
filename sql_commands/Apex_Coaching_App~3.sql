SELECT
    TABLE_NAME,
    COLUMN_ID,
    COLUMN_NAME,
    DATA_TYPE,
    DATA_LENGTH,
    DATA_PRECISION,
    DATA_SCALE,
    NULLABLE,
    DATA_DEFAULT
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN (
    'STUDENTS',
    'TEACHERS',
    'COURSES',
    'BATCHES',
    'ENROLLMENTS',
    'PAYMENTS',
    'ATTENDANCE'
)
ORDER BY TABLE_NAME, COLUMN_ID;